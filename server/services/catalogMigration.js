async function migrateBaselineCatalog() {
  try {
    let migrated = 0;
    for (const song of BASELINE_SONGS) {
      const res = await Track.findOneAndUpdate(
        { provider: song.provider, providerTrackId: song.providerTrackId },
        { $setOnInsert: song },
        { upsert: true, new: true }
      );
      if (res) migrated++;
    }
    console.log(`[ELWO CATALOG] Baseline catalog verified/migrated (${migrated} tracks ensured)`);
  } catch (err) {
    console.error('[ELWO CATALOG] Error migrating baseline songs:', err.message);
  }
}

